// Turns the readable content below into flat keys like "organic.compost.steps.0".
function flatten(content: Record<string, Entry>): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [id, e] of Object.entries(content)) {
    out[`organic.${id}.name`] = e.name
    out[`organic.${id}.summary`] = e.summary
    e.ing.forEach((s, i) => {
      out[`organic.${id}.ing.${i}`] = s
    })
    e.steps.forEach((s, i) => {
      out[`organic.${id}.steps.${i}`] = s
    })
    out[`organic.${id}.use`] = e.use
    out[`organic.${id}.caution`] = e.caution
  }
  return out
}

